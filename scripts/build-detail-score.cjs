// Derive the backtest scorer from the individual-stock page, never a second model.
const fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'public/detail.html'), 'utf8');
function slice(a, b) {
  if (!html.includes(a) || !html.includes(b)) throw Error('Detail score source marker missing');
  return html.slice(html.indexOf(a), html.indexOf(b));
}
const out = '// Generated by scripts/build-detail-score.cjs from public/detail.html.\n' +
  '(function(root){\n"use strict";\n' + slice('const num=', 'function setBanner') +
  slice('function normalizePrices', 'function maProjection') +
  '\nroot.TWDetailScore=function(rows,chips){const R=combineScores(rows,chips.margin,chips.inst,chips.daytrade),E=entryEngine(rows,R);return {setup:R.quality,opportunity:E.opportunity,entry:E.score,hold:E.hold}};\n})(globalThis);\n';
const target = path.join(root, 'public/detail-score-r32.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== out) throw Error('Run node scripts/build-detail-score.cjs');
} else fs.writeFileSync(target, out);
